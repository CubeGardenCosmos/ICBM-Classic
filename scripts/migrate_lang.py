#!/usr/bin/env python3
"""Migrate the 1.12 ``en_US.lang`` of ICBM-Classic to 26.3 translation keys.

Usage:
    python3 -I scripts/migrate_lang.py legacy-1.12/src/main/resources/assets/icbmclassic/lang/en_US.lang \
        > .dev/tmp/en_us.migrated.json

Output:
    stdout: JSON object with the migrated hand written keys (sorted), ready to be merged into
            ``src/main/resources/assets/icbmclassic/lang/en_us.json``
    file:   ``scripts/lang_key_map.json`` -- legacy key -> new key (``null`` = dropped, the value is
            generated by datagen), so later port steps can look up the replacement of a key.

Rules (implementation-manual.md / i18n.md §2):
    * ``tile.*.name``, ``item.*.name``, ``explosive.*.name``, ``missile.*.name``, ``grenade.*.name``,
      ``bombcart.*.name``, ``bomblet.*.name`` and ``itemGroup.icbmclassic`` are generated by
      ``ICBMLanguageProvider`` (datagen) and are therefore not migrated.
    * ``config.icbmclassic:*`` is dropped (i18n.md §2).
    * ``command.icbmclassic:icbm.<x>``        -> ``icbmclassic.command.<x>``
    * ``gui.icbmclassic:<x>``                 -> ``icbmclassic.gui.<x>``
    * ``message.<x>`` / ``chat.<x>`` / ``info.<id>.<x>`` -> ``icbmclassic.message.<x>``
    * ``radio.icbmclassic:message.<x>``       -> ``icbmclassic.radio.<x>``
    * ``gps.<x>.name``                        -> ``icbmclassic.message.gps.<x>``
    * ``potion.<x>``                          -> ``effect.icbmclassic.<x>``
    * ``death.attack.icbm.*`` / ``death.attack.icbmclassic:*`` -> ``death.attack.icbmclassic.*``
    * ``explosive.<id>.<x>`` / ``item.<id>.<x>`` / ``tile.<id>.<x>`` (``x`` != ``name``)
      -> ``icbmclassic.explosive|item|block.<id>.<x>``
    * every other key is listed in ``MANUAL`` below; unknown keys are reported and make the script
      exit with code 2.

Values: ``§x`` colour codes are removed (i18n.md §3), a literal ``\\n``/``\\t`` becomes a real
newline/tab, ``%1$s`` style placeholders are kept unchanged.
"""

import io
import json
import os
import re
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
KEY_MAP_FILE = os.path.join(ROOT, "scripts", "lang_key_map.json")

# --- keys whose value the datagen provider generates -------------------------------------------
GENERATED = re.compile(
    r"^(tile|item|explosive|missile|grenade|bombcart|bomblet)\.icbmclassic:.+\.name$"
)
GENERATED_EXACT = {"itemGroup.icbmclassic"}
DROP = re.compile(r"^config\.icbmclassic:")

# --- 1.12 id -> 26.3 id renames (registry-ids.md; only used for the key, never for the value) ---
ID_RENAMES = {
    "redMatter": "redmatter",
    "emptower": "emp_tower",
    "launcherbase": "launcher_pad",
    "launcherscreen": "launcher_screen",
    "launcherframe": "launcher_frame",
    "radarstation": "radar_station",
    "cruiselauncher": "cruise_launcher",
    "missilecoordinator": "missile_coordinator",
    "batterybox": "battery_box",
    "sulfurDust": "sulfur_dust",
    "poisonPowder": "poison_powder",
    "radarGun": "radar_gun",
    "laserDetonator": "laser_detonator",
    "remoteDetonator": "remote_detonator",
    "rocketLauncher": "rocket_launcher",
    "ballisticLauncher": "ballistic_launcher",
    "explosive_bomblet": "empty_bomblet",
    "frostBite": "frost_bite",
}

# --- 1.12 subtitle key suffix -> 26.3 sound id (registry-ids.md §7) -------------------------
SUBTITLES = {
    "beam.charge": "beam_charging",
    "explosion": "explosion",
    "explosion.antimatter": "antimatter",
    "explosion.collapse": "collapse",
    "explosion.debilitation": "debilitation",
    "explosion.emp": "emp",
    "explosion.fire": "explosion_fire",
    "explosion.redmatter": "redmatter",
    "explosion.sonicwave": "sonic_wave",
    "gas.leak": "gas_leak",
    "machine.hum": "machine_hum",
    "meep": "meep",
    "missile.launch": "missile_launch",
    "missile.movement": "missile_engine",
    "power.down": "power_down",
    "radioactive_tick": "radioactive_tick",
}

# --- shape rules -------------------------------------------------------------------------------
RULES = [
    (re.compile(r"^command\.icbmclassic:icbm\.(.+)$"), r"icbmclassic.command.\1"),
    # gui.icbmclassic:<machine>.<element> and the two unprefixed 1.12 leftovers
    (re.compile(r"^gui\.icbmclassic:(.+)$"), lambda m: "icbmclassic.gui." + shifted(m.group(1))),
    (re.compile(r"^gui\.(launcherscreen|coordinator)\.(.+)$"),
     lambda m: "icbmclassic.gui." + snake(m.group(1)) + "." + m.group(2)),
    # subtitles (S2.09)
    (re.compile(r"^subtitle\.icbmclassic:(.+)$"),
     lambda m: "subtitles.icbmclassic." + SUBTITLES[m.group(1)]),
    # chat/status text of the launcher network, gps tools and the radar gun
    (re.compile(r"^info\.icbmclassic:(.+)$"), r"icbmclassic.message.\1"),
    (re.compile(r"^message\.(.+)$"), lambda m: "icbmclassic.message." + shifted(m.group(1))),
    (re.compile(r"^chat\.(.+)$"), lambda m: "icbmclassic.message." + shifted(m.group(1))),
    # tooltips of the (not yet ported) tools
    (re.compile(r"^info\.(.+)$"), r"icbmclassic.tooltip.\1"),
    (re.compile(r"^radio\.icbmclassic:message\.(.+)$"), r"icbmclassic.radio.\1"),
    (re.compile(r"^gps\.(.+)\.name$"), r"icbmclassic.message.gps.\1"),
    (re.compile(r"^potion\.(.+)$"), lambda m: "effect.icbmclassic." + snake(m.group(1))),
    (re.compile(r"^error\.icbmclassic:projectile\.(.+)$"), r"icbmclassic.error.projectile.\1"),
    (re.compile(r"^projectile\.icbmclassic:([^.]+)\.(.+)$"),
     lambda m: "icbmclassic.projectile." + snake(m.group(1)) + "." + m.group(2)),
    (re.compile(r"^tier\.icbmclassic\.(.+)$"), r"icbmclassic.tier.\1"),
    (re.compile(r"^death\.attack\.icbm\.(.+)$"), r"death.attack.icbmclassic.\1"),
    (re.compile(r"^death\.attack\.icbmclassic:(.+)$"), r"death.attack.icbmclassic.\1"),
    (re.compile(r"^(explosive|item|tile)\.icbmclassic:([^.]+)\.(.+)$"),
     lambda m: "icbmclassic." + {"explosive": "explosive", "item": "item", "tile": "block"}[m.group(1)]
               + "." + snake(m.group(2)) + "." + m.group(3)),
]

# --- exact keys that no shape rule covers ------------------------------------------------------
MANUAL = {
    # 1.12 spelled the laser designator tooltip with a doubled suffix
    "item.icbmclassic:laserDetonator.info.info": "icbmclassic.item.laser_detonator.info",
    # 1.12 kept the rocket launcher preview error at the end of the tooltip; drop the "info" step
    "item.icbmclassic:rocketLauncher.info.creative": "icbmclassic.item.rocket_launcher.creative",
    "gui.launcher.cruise.name": "icbmclassic.gui.cruise_launcher.name",
    # the one ".name" key that is runtime text and not a registry name
    "item.icbmclassic:held_item_missile.sword.name": "icbmclassic.item.held_item_missile.sword.name",
}


def snake(segment):
    """``sulfurDust`` -> ``sulfur_dust``, honouring the id renames from registry-ids.md."""
    if segment in ID_RENAMES:
        return ID_RENAMES[segment]
    return re.sub(r"(?<=[a-z0-9])(?=[A-Z])", "_", segment).lower()


def shifted(rest):
    """Snake case the first segment of ``<machine|topic>.<element...>`` and keep the rest."""
    head, dot, tail = rest.partition(".")
    return snake(head) + dot + tail


def parse_lang(text):
    """``key=value`` pairs of a 1.12 .lang file; ``#`` comments and blank lines are ignored."""
    pairs = []
    for number, raw in enumerate(text.split("\n"), start=1):
        line = raw.strip()
        if not line or line.startswith("#"):
            continue
        if "=" not in line:
            raise SystemExit("line %d is not a key=value pair: %s" % (number, line))
        key, value = line.split("=", 1)
        pairs.append((key.strip(), value.strip()))
    return pairs


def clean_value(value):
    """Strip colour codes, turn the literal ``\\n``/``\\t`` of the old format into real characters."""
    value = re.sub(r"\u00a7.", "", value)
    value = value.replace("\\n", "\n").replace("\\t", "\t")
    return value


def map_key(key):
    """Returns (new key, kind) with kind in {mapped, generated, dropped, unmapped}."""
    if key in MANUAL:
        return MANUAL[key], "mapped"
    if GENERATED.match(key) or key in GENERATED_EXACT:
        return None, "generated"
    if DROP.match(key):
        return None, "dropped"
    for pattern, replacement in RULES:
        match = pattern.match(key)
        if match:
            new_key = replacement(match) if callable(replacement) else pattern.sub(replacement, key)
            return new_key, "mapped"
    return None, "unmapped"


def main(argv):
    if len(argv) != 2:
        raise SystemExit(__doc__)
    with io.open(argv[1], encoding="utf-8") as stream:
        pairs = parse_lang(stream.read())

    migrated = {}
    key_map = {}
    unmapped = []
    counts = {"mapped": 0, "generated": 0, "dropped": 0}
    conflicts = []
    for key, value in pairs:
        new_key, kind = map_key(key)
        if kind == "unmapped":
            unmapped.append(key)
            key_map[key] = None
            continue
        key_map[key] = new_key
        counts[kind] += 1
        if kind != "mapped":
            continue
        if new_key in migrated and migrated[new_key] != clean_value(value):
            conflicts.append(new_key)
        migrated[new_key] = clean_value(value)

    if conflicts:
        for key in conflicts:
            print("conflict: %s gets two different values" % key, file=sys.stderr)
        return 1
    if unmapped:
        for key in unmapped:
            print("unmapped: %s" % key, file=sys.stderr)
        print("%d unmapped keys, add them to MANUAL" % len(unmapped), file=sys.stderr)
        return 2

    with io.open(KEY_MAP_FILE, "w", encoding="utf-8") as stream:
        stream.write(json.dumps(dict(sorted(key_map.items())), indent=2, ensure_ascii=False) + "\n")
    print(json.dumps(migrated, indent=2, ensure_ascii=False, sort_keys=True))
    print("migrated %d, generated %d, dropped %d -> %s"
          % (counts["mapped"], counts["generated"], counts["dropped"], KEY_MAP_FILE), file=sys.stderr)
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv))
